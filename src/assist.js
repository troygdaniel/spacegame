// ---------- Flight assist: tell the ship what to do about a target and it flies itself (card space-game-assist-core) ----------
// Beside the hand flight, not instead of it: Z switches the assist on and off. While it is on, a command key gives the ship an order about the
// target (the one the N list sets, or one handed to assistSet): 1 Approach (fly to it and stop near it), 2 Keep at range (hold a distance, backing
// off when too close). The ship flies like a ship: it turns first, burns when its nose is on the line, and brakes in time. Any flight key
// (W A S D, the arrows, Shift, Q, E) hands the stick back; the guns stay yours (Space fires while the assist flies). The same key again ends the order.
//
// THE INTERFACE (other files build on these names; they do not edit this file or src/space.js):
//   ASSIST_MODES                    the mode table: id -> { id, label, key, cap, range, plan }
//   assistMode(id, def)             add a mode from another file (src/assist_orbit.js): def = { label, key: 'THREE', cap: '3', range, plan }
//                                     range   the default when assistSet gets none: a number of px, or target => px
//                                     plan    (a, me, tgt, st) => { face, burn, brake, done, status }   called once a frame, pure:
//                                               a    the order: { mode, target, range, since }
//                                               me   { x, y, rot, vx, vy, burning }        tgt  { x, y, vx, vy, moving }
//                                               st   { turn, accel, vmax } of the ship (shipStat)
//                                               face rad to turn to (null: hold the heading), burn: main engine, brake: the brake (as S),
//                                               done: the order is finished, status: one word for the HUD
//   assistSet(mode, target, range)  give an order. target: anything with a live x and y (a body of cruiseKnown, a ship sprite, a bare { x, y });
//                                   none = the nav target. range in px; none = the mode's default. Returns true when the ship took the order,
//                                   false when it did not (assist off, no target, docked, dead, cruising, launch lock). assistSet('') ends the order.
//   assistOn(s, on)                 switch the whole assist on or off (what Z does); ASSIST.on says which
//   assistState()                   for a HUD: { on, mode, label, name, range, dist, closing, status, keys: [{ id, label, cap }] }
//   assistSeek(me, tgt, st, stop, back)   the shared planner: come to rest `stop` px from tgt (back: also back off when inside it)
//   assistStep(me, cmd, st, dt)     the flight model, pure: what one frame of a command does to { x, y, rot, vx, vy } (tests fly it in plain Node)
//   ASSIST.readout = false          hides this file's own one-line readout (for a HUD panel that shows the same)
//   space.js   assistSetup(this) in create(); assistFrame(this, time, dt, crs, ap) after autopilotFrame: 'assist' while an order flies the ship;
//              assistDrive(this, dt) after the thrust code and autopilotDrive sets the heading and the velocity
const ASSIST = {
  on: false, s: null, readout: true,
  key: 'Z',                          // on and off
  turn: 0.0036,                      // rad per ms times the ship's turn stat: the hand flight's own rate (space.js)
  drag: 0.55, brakeDrag: 0.12,       // what is left of the speed after a second of coasting, and of braking: the hand flight's own numbers
  align: 0.3,                        // rad: the nose is on the line, the engine may burn
  lead: 1.7,                         // px/s allowed per px left: the brake takes 2.12 off per second, so 1.7 is in time
  dead: 20, slow: 15,                // px either side of the range that count as there; px/s that counts as stopped
  readY: 156, readGap: 18,           // px: the readout's own line, and how far under a toast it sits when one is in the way
  keepRange: 500, shipStop: 150,     // px: Keep at range when none is given; how near Approach stops to a ship
  keys: ['W', 'A', 'S', 'D', 'UP', 'DOWN', 'LEFT', 'RIGHT', 'SHIFT', 'Q', 'E'] // a flight key: the player wants the stick
};
const ASSIST_MODES = {};

const assistWrap = a => Math.atan2(Math.sin(a), Math.cos(a));

function assistMode(id, def) {
  const m = ASSIST_MODES[id] = Object.assign({ id, label: id, key: '', cap: '', range: null, plan: () => ({}) }, def, { id });
  const s = ASSIST.s; if (s && s.as && m.key && !s.as.k[m.key]) s.as.k[m.key] = s.input.keyboard.addKey(m.key); // a mode added after the scene was made
  return m;
}

// how near Approach stops when no range is given: a body as the autopilot does (dock and land range), a ship 150 px off, a bare point on it
function assistStopAt(t) {
  if (t.type) return autopilotStop(t);
  return t.body ? ASSIST.shipStop : 0;
}
function assistVel(t) {
  const v = t.body && t.body.velocity;
  return v ? { x: v.x || 0, y: v.y || 0 } : { x: t.vx || 0, y: t.vy || 0 };
}
function assistName(t) { return t.name || (t.body ? 'the ship' : 'the point'); }
function assistStats() { return { turn: shipStat('turn'), accel: shipStat('accel'), vmax: shipStat('vmax') }; }
function assistKeyLine() { return Object.values(ASSIST_MODES).filter(m => m.cap).map(m => m.cap + ' ' + m.label).join('   '); }

// ---- the flight model and the planner: pure, no scene ----

// one frame of a command. Turn toward cmd.face at the ship's turn rate; burn pushes along the nose; no burn coasts (the speed bleeds as in
// hand flight) or brakes; never faster than the ship's top speed.
function assistStep(me, cmd, st, dt) {
  const dts = dt / 1000; let rot = me.rot, vx = me.vx, vy = me.vy;
  if (cmd.face !== null && cmd.face !== undefined) {
    const d = assistWrap(cmd.face - rot), step = ASSIST.turn * st.turn * dt;
    rot = Math.abs(d) <= step ? assistWrap(cmd.face) : assistWrap(rot + Math.sign(d) * step);
  }
  if (cmd.burn) { vx += Math.cos(rot) * st.accel * dts; vy += Math.sin(rot) * st.accel * dts; }
  else { const k = Math.pow(cmd.brake ? ASSIST.brakeDrag : ASSIST.drag, dts); vx *= k; vy *= k; }
  const sp = Math.hypot(vx, vy); if (sp > st.vmax) { vx *= st.vmax / sp; vy *= st.vmax / sp; }
  return { x: me.x + vx * dts, y: me.y + vy * dts, rot, vx, vy, burning: !!cmd.burn };
}

// come to rest `stop` px from the target (measured to its centre), relative to its own motion. back: when inside that distance, back off to it.
// The speed it wants falls with the distance left, so the brake comes on in time; the engine burns only with the nose on the line.
function assistSeek(me, tgt, st, stop, back) {
  const dx = tgt.x - me.x, dy = tgt.y - me.y, dist = Math.hypot(dx, dy) || 1e-6, ux = dx / dist, uy = dy / dist;
  let left = dist - (stop || 0); if (!back && left < 0) left = 0;
  const there = Math.abs(left) <= ASSIST.dead;
  const want = there ? 0 : Math.sign(left) * Math.min(st.vmax * 1.05, ASSIST.lead * (Math.abs(left) - ASSIST.dead / 2)); // px/s toward the target (1.05: the cruise part never reaches it, so the engine stays lit)
  const rvx = me.vx - (tgt.vx || 0), rvy = me.vy - (tgt.vy || 0), rel = Math.hypot(rvx, rvy);
  const ex = ux * want - rvx, ey = uy * want - rvy, err = Math.hypot(ex, ey); // the change of velocity the ship needs
  const sp = Math.hypot(me.vx, me.vy), toTarget = Math.atan2(dy, dx);
  const out = { face: toTarget, burn: false, brake: false, done: false, status: there ? 'hold' : left < 0 ? 'back off' : 'burn', dist, left, closing: rvx * ux + rvy * uy };
  if (there && rel <= ASSIST.slow) return out; // there and still: nose on the target, engine off
  // what it needs is mostly "slower": the brake does that without a turn
  if (sp > 8 && err > Math.abs(want) * 0.03 + 3 && ex * me.vx + ey * me.vy < -0.7 * err * sp) { out.brake = true; out.status = there ? 'hold' : 'brake'; if (left < 0) out.face = Math.atan2(ey, ex); return out; }
  if (err > ASSIST.dead) out.face = Math.atan2(ey, ex); // turn first: the nose onto the line of the change it needs
  const p = ex * Math.cos(out.face) + ey * Math.sin(out.face), aligned = Math.abs(assistWrap(out.face - me.rot)) < ASSIST.align;
  out.burn = aligned && (p > Math.abs(want) * 0.1 + 4 || (!!me.burning && p > 0));
  if (!out.burn && !aligned) out.status = 'turn';
  return out;
}

assistMode('approach', { label: 'Approach', key: 'ONE', cap: '1', range: assistStopAt,
  plan: (a, me, tgt, st) => { const c = assistSeek(me, tgt, st, a.range, false); if (c.status === 'hold' && !c.brake && !tgt.moving) c.done = true; return c; } });
assistMode('keep', { label: 'Keep at range', key: 'TWO', cap: '2', range: ASSIST.keepRange,
  plan: (a, me, tgt, st) => assistSeek(me, tgt, st, a.range, true) });

// ---- the scene side ----

function assistSetup(s) {
  ASSIST.s = s;
  const a = s.as = { mode: '', target: null, nav: null, range: 0, since: 0, burning: false, cmd: null, held: {}, readAt: 0 };
  a.k = s.input.keyboard.addKeys([ASSIST.key].concat(Object.values(ASSIST_MODES).map(m => m.key).filter(Boolean)).join(','));
  a.read = s.add.text(W / 2, ASSIST.readY, '', { fontFamily: 'monospace', fontSize: '16px', fontStyle: 'bold', color: '#9fe9ff' }).setOrigin(0.5).setScrollFactor(0).setDepth(102).setStroke('#02060d', 4).setVisible(false);
  s.events.once('shutdown', () => { if (ASSIST.s === s) ASSIST.s = null; });
}

function assistOn(s, on) {
  const a = s && s.as; if (!a) return false;
  ASSIST.on = !!on;
  if (!ASSIST.on && a.mode) assistStop(s, 'quiet');
  toast(s, ASSIST.on ? 'Flight assist on.   ' + assistKeyLine() : 'Flight assist off.', '#9fe9ff'); sfx(ASSIST.on ? 'chime' : 'tick');
  a.readAt = 0;
  return ASSIST.on;
}

function assistTarget(s) { return (s.cr && s.cr.target) || null; }

function assistSet(mode, target, range) {
  const s = ASSIST.s, a = s && s.as; if (!a) return false;
  if (!mode) { if (a.mode) assistStop(s, 'quiet'); return true; }
  const m = ASSIST_MODES[mode];
  if (!m || !ASSIST.on || s.dead || s.leaving || s.jmp || s.cruising || s.time.now < (s.lockUntil || 0)) return false;
  const t = target || assistTarget(s);
  if (!t) { toast(s, 'No target. Press N and pick one.', '#ffd37a'); sfx('empty'); return false; }
  if (s.ap && s.ap.on) autopilotEnd(s, 'quiet');
  a.mode = mode; a.target = t; a.nav = assistTarget(s); a.since = s.time.now; a.burning = false; a.cmd = null; a.readAt = 0;
  a.range = typeof range === 'number' && range >= 0 ? range : typeof m.range === 'function' ? m.range(t) : (m.range || 0);
  a.held = {}; ASSIST.keys.forEach(n => { if (s.k && s.k[n] && s.k[n].isDown) a.held[n] = true; }); // a key already down when the order came is not a new wish for the stick
  toast(s, m.label + ': ' + assistName(t) + (a.range ? ' at ' + hudFmt(a.range / 10) + ' km' : '') + '. Any flight key takes the stick back.', '#9fe9ff'); sfx('chime');
  return true;
}

function assistStop(s, why) {
  const a = s.as, t = a.target, m = ASSIST_MODES[a.mode];
  a.mode = ''; a.target = null; a.burning = false; a.cmd = null; a.readAt = 0;
  if (why === 'arrived') { toast(s, m.label + ' done: ' + assistName(t) + '.', '#6dff9c'); sfx('chime'); }
  else if (why === 'key') { toast(s, 'You have the stick.', '#9fe9ff'); sfx('tick'); }
  else if (why === 'lost') { toast(s, 'Target lost. You have the stick.', '#ffd37a'); sfx('empty'); }
  // 'quiet': a dock, a death, a jump, a cruise, the autopilot, the assist switched off: that event says its own line
}

function assistState() {
  const s = ASSIST.s, a = s && s.as, m = a && ASSIST_MODES[a.mode], c = a && a.cmd;
  const keys = Object.values(ASSIST_MODES).map(x => ({ id: x.id, label: x.label, cap: x.cap }));
  if (!m) return { on: ASSIST.on, mode: '', label: '', name: '', range: 0, dist: 0, closing: 0, status: '', keys };
  const t = a.target, v = assistVel(t), b = s.ship.body.velocity, dx = t.x - s.ship.x, dy = t.y - s.ship.y, dist = Math.hypot(dx, dy) || 1e-6;
  return { on: ASSIST.on, mode: m.id, label: m.label, name: assistName(t), range: a.range, dist, closing: ((b.x - v.x) * dx + (b.y - v.y) * dy) / dist, status: (c && c.status) || '', keys };
}

const assistJustDown = k => { if (k && k._justDown) { k._justDown = false; return true; } return false; }; // what Phaser's JustDown does

// one call per frame from Space.update, after autopilotFrame (crs and ap are what cruise and the autopilot returned)
function assistFrame(s, time, dt, crs, ap) {
  const a = s.as; if (!a) return '';
  if (s.dead || s.leaving) { if (a.mode) assistStop(s, 'quiet'); return ''; }
  const nav = crs === 'nav'; // the nav list has the keyboard
  if (assistJustDown(a.k[ASSIST.key]) && !nav) assistOn(s, !ASSIST.on);
  for (const m of Object.values(ASSIST_MODES)) {
    if (!m.key || !assistJustDown(a.k[m.key]) || nav || !ASSIST.on) continue;
    if (a.mode === m.id) { assistStop(s, 'key'); break; }
    // a new order while one flies keeps that order's target, unless the nav target has been changed since (the game drops the nav target near its body)
    const nt = assistTarget(s);
    assistSet(m.id, nt && nt !== a.nav ? nt : a.target || nt || undefined);
    break;
  }
  assistRead(s, time);
  if (!ASSIST.on || !a.mode) return '';
  if (crs === 'cruise' || ap === 'cruise' || ap === 'auto' || s.jmp) { assistStop(s, 'quiet'); return ''; } // cruise, the autopilot or a jump charge has the ship
  if (a.target.active === false) { assistStop(s, 'lost'); return ''; } // a ship that is gone
  for (const n of ASSIST.keys) {
    const down = !!(s.k[n] && s.k[n].isDown);
    if (!down) delete a.held[n]; else if (!a.held[n]) { assistStop(s, 'key'); return ''; }
  }
  return 'assist';
}

// the order flies the ship: called after the thrust code, so its heading and velocity stand
function assistDrive(s, dt) {
  const a = s.as; if (!a || !a.mode) return;
  const ship = s.ship, b = ship.body, st = assistStats(), t = a.target, tv = assistVel(t);
  const me = { x: ship.x, y: ship.y, rot: ship.rotation, vx: b.velocity.x, vy: b.velocity.y, burning: a.burning };
  const cmd = ASSIST_MODES[a.mode].plan(a, me, { x: t.x, y: t.y, vx: tv.x, vy: tv.y, moving: Math.hypot(tv.x, tv.y) > 1 }, st) || {};
  const n = assistStep(me, cmd, st, dt);
  ship.rotation = n.rot; a.burning = n.burning; a.cmd = cmd;
  b.setAcceleration(0, 0).setDrag(0).setMaxSpeed(st.vmax + 10); // the model above has the drag in it; the next frame of hand flight sets its own again
  b.setVelocity(n.vx, n.vy);
  if (cmd.burn && s.trail) s.trail.emitParticleAt(ship.x - Math.cos(n.rot) * 20, ship.y - Math.sin(n.rot) * 20, 2);
  if (cmd.done) assistStop(s, 'arrived');
}

// this file's own readout, one line under the autopilot's: what the assist is doing, or the command keys while it waits for an order
// where the readout sits: its own line (y 156), or just under the lowest toast still up when one reaches that far down (toasts stack from y 96
// and are drawn over everything, so the line used to be half hidden behind the second one: docs/CRITIC.md run 1, finding 2)
function assistReadY(toasts) {
  let low = 0;
  (toasts || []).forEach(o => { if (o && o.t && o.t.active) low = Math.max(low, o.y + o.h / 2); });
  return low + ASSIST.readGap > ASSIST.readY - 10 ? Math.round(low + ASSIST.readGap) : ASSIST.readY;
}
function assistRead(s, time) {
  const a = s.as, show = ASSIST.readout && ASSIST.on;
  a.read.setVisible(show);
  if (show) a.read.setY(assistReadY(s.toasts)); // every frame, not every 200 ms: a toast can come up at any time
  if (!show || time < a.readAt) return;
  a.readAt = time + 200;
  const st = assistState();
  a.read.setText(st.mode ? 'ASSIST  ' + st.label.toUpperCase() + '  ' + st.name.toUpperCase() + '   ' + hudFmt(st.dist / 10) + ' km' + (st.status ? '   ' + st.status.toUpperCase() : '')
    : assistTarget(s) ? 'ASSIST ON   ' + assistKeyLine() + '   Z off'
    : 'ASSIST ON   no target: press N and pick one   Z off'); // short, so it stays clear of the mission panel on its left; the keys mean nothing without a target
}
